<?php

namespace App\Game\Enum;

/**
 * Ключевые слова, которые проверяют правила (кого можно атаковать, кто атакует сразу, куда ляжет ландшафт).
 * Их дают способности (KeywordAbilityInterface) — в том числе на время, по условию.
 */
enum Keyword: string
{
    case Taunt = 'taunt';       // пока на поле — атаковать можно только её
    case Charge = 'charge';     // атакует в ход выкладки
    case Flying = 'flying';     // атаковать может только существо с полётом
    case Cover = 'cover';       // укрытие (туман): существо нельзя атаковать; Провокация его снимает
    case Hostile = 'hostile';   // враждебный ландшафт: ложится на половину поля противника
}
